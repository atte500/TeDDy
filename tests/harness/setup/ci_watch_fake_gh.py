"""Fake ``gh`` test double for the shipped ``make ci-watch`` target.

The shipped target shells out to ``gh`` (``run list``, ``run view``, ``run
watch``) and pipes the JSON through ``--jq`` programs. This harness models a
deterministic CI scenario and writes a POSIX ``gh`` shim that serves exactly
those subcommands, so the real target bytes run unmodified against synthetic
data. The shim mirrors the real CLI contract by applying ``--jq`` to the JSON it
would otherwise print.

The shim is a Python script with an ``env python3`` shebang: it keeps JSON
handling readable and avoids a hard dependency on a system ``jq``. The shim
recognises the exact ``--jq`` programs the target passes and fails loudly on an
unknown program, so the harness cannot silently drift from the target.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

__all__ = ["CiWatchScenario", "JobResult", "RunResult"]


@dataclass(frozen=True)
class JobResult:
    """A CI job within a run, with the conclusions of its steps."""

    name: str
    conclusion: str
    steps: tuple[tuple[str, str], ...] = ()


@dataclass(frozen=True)
class RunResult:
    """A CI workflow run registered for one commit."""

    database_id: int
    workflow: str
    head_sha: str
    conclusion: str
    jobs: tuple[JobResult, ...] = ()
    log: str = ""


@dataclass(frozen=True)
class CiWatchScenario:
    """A deterministic CI scenario served by the fake ``gh`` shim."""

    runs: tuple[RunResult, ...] = ()

    def write(self, scenario_dir: Path) -> Path:
        """Writes the scenario data and the executable ``gh`` shim.

        Returns the path of the generated shim so callers can assert on it.
        """
        scenario_dir = Path(scenario_dir)
        bin_dir = scenario_dir / "bin"
        bin_dir.mkdir(parents=True, exist_ok=True)
        (scenario_dir / "scenario.json").write_text(
            json.dumps(self._as_payload(), indent=2), encoding="utf-8"
        )
        shim = bin_dir / "gh"
        shim.write_text(_FAKE_GH_SCRIPT, encoding="utf-8")
        shim.chmod(0o755)
        return shim

    def _as_payload(self) -> dict:
        return {
            "runs": [
                {
                    "databaseId": run.database_id,
                    "workflow": run.workflow,
                    "headSha": run.head_sha,
                    "conclusion": run.conclusion,
                    "jobs": [
                        {
                            "name": job.name,
                            "conclusion": job.conclusion,
                            "steps": [
                                {"name": name, "conclusion": conclusion}
                                for name, conclusion in job.steps
                            ],
                        }
                        for job in run.jobs
                    ],
                    "log": run.log,
                }
                for run in self.runs
            ]
        }


_FAKE_GH_SCRIPT = r'''#!/usr/bin/env python3
"""Fake ``gh`` shim serving one deterministic CI scenario.

Generated by tests/harness/setup/ci_watch_fake_gh.py. It models only the ``gh``
subcommands the shipped ``make ci-watch`` target uses: ``run list``, ``run view``
(including ``--log-failed``), and ``run watch``. When the target passes ``--jq``,
the shim filters the JSON through the same program, mirroring the real CLI
contract, so the shipped target bytes run unmodified against synthetic data.
"""
import json
import os
import sys


def _log_invocation(argv):
    log_path = os.environ.get("FAKE_GH_LOG")
    if log_path:
        with open(log_path, "a", encoding="utf-8") as handle:
            handle.write(" ".join(argv) + "\n")


def _load_runs():
    scenario_dir = os.environ["FAKE_GH_SCENARIO"]
    with open(os.path.join(scenario_dir, "scenario.json"), encoding="utf-8") as handle:
        return json.load(handle)["runs"]


def _parse(argv):
    flags = {}
    positionals = []
    index = 0
    while index < len(argv):
        token = argv[index]
        if token.startswith("--"):
            following = argv[index + 1] if index + 1 < len(argv) else None
            if following is not None and not following.startswith("--"):
                flags[token[2:]] = following
                index += 2
                continue
            flags[token[2:]] = True
            index += 1
            continue
        positionals.append(token)
        index += 1
    return flags, positionals


def _run_to_json(run, fields):
    available = {
        "workflowName": run["workflow"],
        "databaseId": run["databaseId"],
        "conclusion": run["conclusion"],
        "jobs": [
            {
                "name": job["name"],
                "conclusion": job["conclusion"],
                "steps": [
                    {"name": step["name"], "conclusion": step["conclusion"]}
                    for step in job.get("steps", [])
                ],
            }
            for job in run.get("jobs", [])
        ],
    }
    return {field: available[field] for field in fields}


def _apply_jq(data, program):
    if program == ".[].workflowName":
        return "\n".join(item["workflowName"] for item in data)
    if program == ".[0].databaseId":
        return str(data[0]["databaseId"]) if data else ""
    if program == ".conclusion":
        return data["conclusion"]
    if program == ".jobs | length":
        return str(len(data["jobs"]))
    if program == '[.jobs[] | select(.conclusion=="failure") | .name] | sort | join(",")':
        names = sorted(
            job["name"] for job in data["jobs"] if job["conclusion"] == "failure"
        )
        return ",".join(names)
    if program == '[.jobs[] | select(.conclusion=="failure") | .steps[]? | select(.conclusion=="failure") | .name] | sort | join(", ")':
        names = sorted(
            step["name"]
            for job in data["jobs"]
            if job["conclusion"] == "failure"
            for step in job.get("steps", [])
            if step["conclusion"] == "failure"
        )
        return ", ".join(names)
    sys.stderr.write("fake gh: unsupported --jq program: %r\n" % program)
    sys.exit(2)


def _emit(data, flags):
    program = flags.get("jq")
    if program:
        sys.stdout.write(_apply_jq(data, program))
    else:
        sys.stdout.write(json.dumps(data))
    sys.stdout.write("\n")


def main():
    argv = sys.argv[1:]
    _log_invocation(argv)
    if len(argv) < 2 or argv[0] != "run":
        sys.stderr.write("fake gh: unsupported command: %s\n" % " ".join(argv))
        sys.exit(2)
    group = argv[1]
    flags, positionals = _parse(argv[2:])
    runs = _load_runs()
    if group == "list":
        commit = flags.get("commit")
        workflow = flags.get("workflow")
        selected = [
            run
            for run in runs
            if (commit is None or run["headSha"] == commit)
            and (workflow is None or run["workflow"] == workflow)
        ]
        fields = str(flags["json"]).split(",")
        _emit([_run_to_json(run, fields) for run in selected], flags)
        return
    if group == "view":
        run = next(run for run in runs if run["databaseId"] == int(positionals[0]))
        if flags.get("log-failed"):
            sys.stdout.write(run.get("log", ""))
            return
        fields = str(flags["json"]).split(",")
        _emit(_run_to_json(run, fields), flags)
        return
    if group == "watch":
        run = next(run for run in runs if run["databaseId"] == int(positionals[0]))
        sys.exit(0 if run["conclusion"] == "success" else 1)
    sys.stderr.write("fake gh: unsupported run subcommand: %s\n" % group)
    sys.exit(2)


main()
'''
